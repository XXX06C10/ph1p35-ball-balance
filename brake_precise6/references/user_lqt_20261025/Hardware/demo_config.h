/**
  ******************************************************************************
  * @file    demo_config.h
  * @brief   针对 MS42CG + D36A 硬件平台的用户可调参数配置文件
  ******************************************************************************
  *
  * ======== 文件用途 ========
  *
  * 本文件集中管理该工程所有用户可调的配置参数, 包括:
  *   - 实验选择(运行哪个演示实验)
  *   - 编码器参数(线数、方向符号、每圈计数值)
  *   - 电机方向极性(DIR 引脚的高/低电平对应编码器正向)
  *   - 闭环参数(控制周期、到位容差)
  *   - 各实验的运行时参数(频率、步数、切换时间等)
  *
  * ======== 修改须知 ========
  *
  * 修改本文件中的任何宏定义后, 必须重新编译并下载到芯片才能生效。
  *
  * 特别注意:
  *   - D36A_MICROSTEP 定义在 motor.h 中(而非本文件),
  *     修改 D36A 驱动器上的拨码开关后, 必须同步修改 motor.h 中的宏,
  *     否则实际转动角度将与计算值不符
  *   - ENCODER_COUNTS_PER_REV 必须与编码器实际线数一致:
  *     MS42CG A/B 相为 1000 线, 经硬件 QEI 四倍频后每圈 = 1000 × 4 = 4000 计数
  *   - 闭环控制以 A/B 编码器计数值为位置单位, 不是角度或毫米
  ******************************************************************************
  */
#ifndef DEMO_CONFIG_H
#define DEMO_CONFIG_H

/*
 * ── 实验选择 (DEMO_SELECT) ──
 *
 * 通过修改此宏的值选择上电后运行哪个实验:
 *
 *   1 = 开环正反转实验
 *       电机每隔 1 秒自动正反转换向, 每次转动 DEMO1_STEPS 步。
 *       用于验证电机驱动器 STEP/DIR/EN 接线是否正确, 不依赖编码器。
 *
 *   2 = 编码器数据采集实验
 *       串口发 '1'/'2'/'0' 控制电机连续转/停止。
 *       每 200ms 自动打印 A/B 计数值、角度、速度、PWM 绝对角度、Z 相圈数。
 *       用于验证编码器四路信号(A/B/PWM/Z)均正常。
 *
 *   3 = 闭环自动演示实验
 *       电机自动在 ±DEMO3_TARGET_DEG 间来回往复,
 *       每 4 秒切换一次目标。用于观察闭环收敛过程。
 *
 *   4 = 串口角度指令闭环控制实验
 *       通过串口 ASCII 指令交互式控制电机转动任意角度,
 *       支持查询状态、设零、停止、清除故障、翻转方向极性。
 */
#define DEMO_SELECT                 3

/*
 * ── 电机数量 (MOTOR_COUNT) ──
 *
 * 当前硬件只使用电机1, 固定为 1。
 * 如需扩展到两个电机, 改为 2 并相应添加第二套硬件连接和状态变量。
 */
#define MOTOR_COUNT                 1

/*
 * ── 编码器每圈计数值 (ENCODER_COUNTS_PER_REV) ──
 *
 * MS42CG 编码器 A/B 相原始分辨率为 1000 线/圈。
 * TIMG8 硬件 QEI 配置为 2 输入模式(X2), 进一步对 A/B 的上升沿和下降沿
 * 均进行计数(X4), 因此最终每圈计数值 = 1000 × 4 = 4000。
 *
 * 此值是所有角度/速度换算的基准, 必须与实际硬件一致。
 */
#define ENCODER_COUNTS_PER_REV      4000U

/*
 * ── A/B 编码器计数方向符号 (ENCODER_AXIS_X_SIGN) ──
 *
 * 当编码器 A/B 相接线与电机实际运动方向不一致时,
 * 将此值改为 -1 即可将计数方向取反。
 *
 * 判断方法:
 *   运行实验2, 发 '1' 使电机顺时针转。
 *   如果打印的 AB 计数值在大幅减小(而非增大), 说明符号反了,
 *   将此宏改为 -1。
 *
 * 注意: 此宏只影响应用层读取的编码器计数值的符号,
 *       不影响硬件 QEI 的原始计数。
 */
#define ENCODER_AXIS_X_SIGN         1

/*
 * ── DIR 引脚正向电平 (AXIS_X_POSITIVE_DIR_LEVEL) ──
 *
 * 定义当 DIR 引脚为何种电平时, 编码器计数为正向增加。
 *
 *   1U = DIR 高电平时编码器正向计数
 *   0U = DIR 低电平时编码器正向计数
 *
 * 判断方法:
 *   如果设置了目标角度后, 编码器反馈显示电机在反向运动,
 *   说明此宏配置与接线不一致。可以在实验4 中用 D1 指令动态翻转,
 *   确认正确后将此宏设为对应的值。
 *
 * 电机2(Y轴)的同名宏暂未使用, 留作扩展。
 */
#define AXIS_X_POSITIVE_DIR_LEVEL   1U
#define AXIS_Y_POSITIVE_DIR_LEVEL   1U

/*
 * ── 闭环控制周期 (CL_PERIOD_MS) ──
 *
 * 闭环每 5ms 执行一次(在 TIMG0 ZERO 中断中调用 CL_Process)。
 *
 * 选择 5ms 的理由:
 *   - 足够短以保证位置跟踪的实时性
 *   - 每次脉冲爆发最多2步，在最慢频率400Hz下耗时约5ms
 *   - ISR 执行时间(<1ms)远小于 5ms, 不会丢失中断
 *
 * 如需更改:
 *   - 减小此值可提高响应速度, 但需确保脉冲爆发能在更短时间内完成
 *   - 增大此值可降低 CPU 占用, 但响应会变慢
 */
#define CL_PERIOD_MS                5U

/*
 * ── 闭环到位容差 (CL_TOLERANCE_COUNTS) ──
 *
 * 当编码器位置与目标位置的偏差的绝对值 ≤ 此值, 并连续稳定
 * CL_SETTLE_CYCLES(3) 个控制周期后, 判定电机已到位。
 *
 * 当前值 = 2 计数, 换算为角度:
 *   2 / 4000 × 360° ≈ 0.18°
 *
 * 在当前机械精度下, 0.18° 的容差已经远小于齿轮间隙和皮带弹性带来的误差。
 *
 * 如需更高的到位速度(允许更大的稳态误差), 可适当增大此值。
 */
#define CL_TOLERANCE_COUNTS         2U

/*
 * ======== 以下为各实验的运行时参数 ========
 */

/*
 * ── 实验1: 开环正反转 ──
 *
 * DEMO1_STEPS        每次转向后发出的 STEP 脉冲数。
 *                    默认 = MOTOR_STEPS_PER_REV / 4 = 800 步 = 90°。
 * DEMO1_FREQ_HZ      STEP 脉冲频率(Hz), 决定电机转速。
 *                    频率越高转得越快, 但过高可能因力矩不足导致丢步。
 *
 * 安全提示: 首次测试时应使用较小的 DEMO1_STEPS(如 200 步),
 *           防止滑台撞击机械限位。
 */
#define DEMO1_STEPS                 (MOTOR_STEPS_PER_REV / 4U)
#define DEMO1_FREQ_HZ               800U

/*
 * ── 实验2: 编码器数据采集 ──
 *
 * DEMO2_FREQ_HZ      连续转动时的 STEP 频率(Hz)。
 * DEMO2_PRINT_MS     两次数据打印之间的间隔(毫秒)。
 *                    默认 200ms, 即每秒打印 5 次。
 */
#define DEMO2_FREQ_HZ               800U
#define DEMO2_PRINT_MS              200U

/*
 * ── 实验3: 闭环自动演示 ──
 *
 * DEMO3_TARGET_DEG   每次切换的目标角度(°)。电机将在
 *                    +DEMO3_TARGET_DEG → 0 → -DEMO3_TARGET_DEG → 0
 *                    四个目标间循环切换。
 *                    (实际物理含义取决于编码器读数, 未做重力/惯量补偿)
 *
 * DEMO3_SWITCH_MS    两次目标切换之间的间隔(毫秒)。
 *                    默认 4000ms = 4 秒, 留给电机足够时间完成运动。
 *
 * DEMO3_OUTPUT_MODE  数据输出模式:
 *                    0 = 普通文本格式, 约 50ms 打印一行
 *                    1 = 上位机格式 {B目标:实际:偏差}$,
 *                        每个控制周期(5ms)输出一帧, 适合绘图工具
 *
 * DEMO3_OUTPUT_MS    数据打印周期(毫秒), 仅 OUTPUT_MODE=0 时有效。
 */
#define DEMO3_TARGET_DEG            5.0f
#define DEMO3_SWITCH_MS             4000U
#define DEMO3_OUTPUT_MODE           0
#define DEMO3_OUTPUT_MS             20U

/*
 * ── 编译期参数校验 ──
 *
 * 确保 DEMO_SELECT 和 MOTOR_COUNT 的取值在合法范围内。
 * 若超出范围, 编译器产生 #error 阻止编译, 防止烧录无效配置。
 */
#if (DEMO_SELECT < 1) || (DEMO_SELECT > 4)
#error "DEMO_SELECT 必须在 1~4 之间"
#endif
#if (MOTOR_COUNT < 1) || (MOTOR_COUNT > 2)
#error "MOTOR_COUNT 必须为 1 或 2"
#endif

#endif
